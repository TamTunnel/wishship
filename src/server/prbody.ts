import type { CheckResult, Tier, Wish } from "./store";
import { scanSecrets } from "./secretscan";

export interface PrBodyInput {
  wish: Wish;
  votes: number;
  backend: string;
  tier: Tier;
  checks: CheckResult[];
  durationMs: number | null;
  costUsd: string | null;
  runId: string;
  filesChanged: string[];
  /** Maintainer churn override applied to this run (see verify.ts). */
  churnOverride?: boolean;
}

/**
 * The PR body is the product's reputation: a maintainer must be able to
 * judge the PR in under a minute. It carries the wish, the vote count,
 * the backend, the FULL verification report (including PARTIAL caveats),
 * duration/cost, and a clear generated-by-an-agent disclosure. It never
 * carries tokens, and never carries full check output (that stays in
 * the run record on the board).
 *
 * Two hardening rules:
 * - The wish body is blockquoted, never raw: a wish containing a fake
 *   "## Verification" section used to spoof the report section below.
 * - A wish body with secret-shaped material is WITHHELD entirely, not
 *   quoted: the old code shipped wish bodies verbatim into PRs.
 */
export function buildPrBody(input: PrBodyInput): string {
  const lines: string[] = [];
  lines.push(`## Wish`);
  lines.push(``);
  lines.push(`**${input.wish.title}** — ${input.votes} vote${input.votes === 1 ? "" : "s"}`);
  lines.push(``);
  if (input.wish.body) {
    const secretHits = scanSecrets(input.wish.body);
    if (secretHits.length > 0) {
      lines.push(
        `> [Wish body withheld: secret-shaped material detected (${secretHits.join(", ")}). ` +
          `See the wish on the board; do not paste secrets into wishes.]`,
      );
    } else {
      for (const line of input.wish.body.split("\n")) {
        lines.push(`> ${line}`);
      }
    }
    lines.push(``);
  }
  if (input.filesChanged.length > 0) {
    lines.push(`## Changed files`);
    lines.push(``);
    for (const f of input.filesChanged) lines.push(`- \`${f}\``);
    lines.push(``);
  }
  lines.push(`## Verification — ${input.tier}`);
  lines.push(``);
  lines.push(
    `> "Verified" means the checks below ran with the reported results. ` +
      `It does not mean the code is correct, secure, or free of subtle ` +
      `backdoors. Please review before merging.`,
  );
  lines.push(``);
  lines.push(`| Check | Result | Detail |`);
  lines.push(`|-------|--------|--------|`);
  for (const c of input.checks) {
    lines.push(`| ${c.name} | ${c.status} | ${oneLine(c.detail)} |`);
  }
  lines.push(``);
  const skipped = input.checks.filter((c) => c.status === "skipped");
  if (skipped.length > 0) {
    lines.push(
      `**Caveats:** ${skipped.map((c) => `${c.name}: ${oneLine(c.detail)}`).join("; ")}`,
    );
    lines.push(``);
  }
  const flagged = input.checks.filter((c) => c.status === "flagged");
  if (flagged.length > 0) {
    lines.push(
      `**Flags for the reviewer:** ${flagged.map((c) => `${c.name}: ${oneLine(c.detail)}`).join("; ")}`,
    );
    lines.push(``);
  }
  if (input.tier === "PARTIAL") {
    lines.push(
      `This PR is PARTIAL: no check failed, but at least one applicable ` +
        `check could not run. See the caveats above.`,
    );
    lines.push(``);
  }
  if (input.churnOverride) {
    lines.push(
      `**Maintainer override:** a maintainer attested that the unrelated ` +
        `files in this diff are legitimate for this wish, overriding the ` +
        `churn-size block for this run. The override is recorded in the ` +
        `run record and audit log. It does not waive the backdoor check: ` +
        `an unrelated file with a new outbound call still blocks.`,
    );
    lines.push(``);
  }
  lines.push(`## Run`);
  lines.push(``);
  lines.push(`- Backend: ${input.backend}`);
  lines.push(
    `- Duration: ${input.durationMs === null ? "unknown" : `${Math.round(input.durationMs / 1000)}s`}`,
  );
  lines.push(
    `- Cost: ${input.costUsd === null ? "not reported by backend (time-bounded only)" : `$${input.costUsd}`}`,
  );
  lines.push(`- Run id: ${input.runId}`);
  lines.push(``);
  lines.push(
    `---\n*Generated by an agent via WishShip. This is a draft PR: ` +
      `review it, request changes, or close it. The agent never merges.*`,
  );
  return lines.join("\n");
}

function oneLine(s: string): string {
  return s.replace(/\s+/g, " ").slice(0, 300);
}
